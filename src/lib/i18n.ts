export function getLangFromCookies(): Language {
  if (typeof document !== 'undefined') {
    const match = document.cookie.match(/(?:^|;)\s*pola-language=([^;]+)/);
    if (match) {
      const lang = match[1];
      if (lang === "en" || lang === "nl") return lang as Language;
    }
  }
  return "id";
}
